import { PGlite } from '@electric-sql/pglite';
import { readFile, readdir } from 'node:fs/promises';
import assert from 'node:assert/strict';
const db = new PGlite();
const q = (sql, args = []) => db.query(sql, args);
let checks = 0;
const equal = (a, b) => { assert.deepEqual(a, b); checks++; };
const reject = async (fn, pattern) => { await assert.rejects(fn, pattern); checks++; };
try {
  await db.exec(`create schema auth;create role anon nologin;create role authenticated nologin;create table auth.users(id uuid primary key,email text,raw_user_meta_data jsonb default '{}');create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid$$;grant usage on schema auth to authenticated,anon;grant execute on function auth.uid() to authenticated,anon;`);
  for (const file of (await readdir('supabase/migrations')).filter(f => f.endsWith('.sql')).sort()) await db.exec((await readFile('supabase/migrations/' + file, 'utf8')).replace('create extension if not exists pgcrypto;', ''));
  const people = ['admin', 'teacher', 'front', 'viewer', 'counselor', 'pending', 'coordinator', 'other'];
  const ids = Object.fromEntries(people.map((name, i) => [name, '00000000-0000-4000-8000-' + String(i + 1).padStart(12, '0')]));
  for (const [name, id] of Object.entries(ids)) await q('insert into auth.users(id,email) values($1,$2)', [id, name + '@example.test']);
  const [campus, otherCampus] = (await q("insert into public.branches(name,code) values('MajorTila','MJ'),('Other campus','OT') returning id")).rows.map(r => r.id);
  for (const [name, role] of [['admin', 'super_admin'], ['teacher', 'teacher'], ['front', 'front_desk'], ['viewer', 'viewer'], ['counselor', 'counselor'], ['coordinator', 'academic_coordinator'], ['other', 'teacher']]) await q('update public.profiles set role_id=(select id from public.roles where name=$1),branch_id=$2,is_active=true where id=$3', [role, name === 'other' ? otherCampus : campus, ids[name]]);
  async function as(name) { await db.exec('reset role'); await q("select set_config('request.jwt.claim.sub',$1,false)", [ids[name] || '']); await db.exec(name === 'anon' ? 'set role anon' : 'set role authenticated'); }
  const write = async (action, payload) => (await q('select public.desk_write($1,$2) result', [action, payload])).rows[0].result;
  const club = async (action, payload) => (await q('select public.desk_club_write($1,$2) result', [action, payload])).rows[0].result;
  const snap = async () => (await q('select public.desk_snapshot() result')).rows[0].result;
  const day = async (c = campus, d = '2026-09-20') => (await q('select public.desk_club_day($1,$2) result', [c, d])).rows[0].result;
  const roster = async (c = campus, d = '2026-09-20') => (await q('select public.desk_club_roster($1,$2) result', [c, d])).rows[0].result;
  await as('admin');
  const course = (await write('save_course', { name: 'IELTS Regular', short_code: 'REG', default_duration_days: 90 })).id;
  const makeBatch = async (code, branch = campus, teacher = null) => (await write('save_batch', { course_type_id: course, branch_id: branch, batch_code: code, teacher_id: teacher, status: 'running' })).id;
  const b1 = await makeBatch('REG-301', campus, ids.teacher), b2 = await makeBatch('REG-302'), b3 = await makeBatch('REG-OTHER', otherCampus, ids.other);
  async function student(name, phone, batch, branch = campus) { return (await write('create_student', { core: { full_name: name, primary_phone: phone, primary_branch_id: branch, status: 'active', joining_date: '2026-09-01' }, batch_id: batch })).id; }
  const s1 = await student('First Student', '01711111111', b1), s2 = await student('Second Student', '01722222222', b2), s3 = await student('Other Student', '01733333333', b3, otherCampus);
  const enrollment = async id => (await snap()).students.find(s => s.id === id).enrollments[0].id;
  const e1 = await enrollment(s1), e2 = await enrollment(s2), e3 = await enrollment(s3);
  const e1b = (await write('add_enrollment', { student_id: s1, batch_id: b2, enrollment_date: '2026-09-01', status: 'active' })).id;
  await db.exec('reset role');
  await q("update public.enrollments set enrollment_date='2026-09-01' where id=any($1::uuid[])", [[e1, e2, e3]]);
  await as('teacher');
  equal((await snap()).students.length, 1);
  const directory = await roster();
  equal(directory.length, 3);
  equal(directory.some(r => r.student_id === s2), true);
  equal(directory.some(r => r.student_id === s3), false);
  equal(Object.keys(directory[0]).sort(), ['enrollment_id', 'student_id', 'full_name', 'student_code', 'batch_id', 'batch_code', 'course_code', 'course_name', 'enrollment_date', 'enrollment_status'].sort());
  equal((await q('select id from public.students where id=$1', [s2])).rows.length, 0);
  const payload = { branch_id: campus, club_date: '2026-09-20', module: 'speaking', enrollment_ids: [e1b, e2] };
  let result = await club('import', payload);
  equal(result.added, 2);
  equal((await day()).attendance.length, 1);
  equal((await day()).attendance[0].student_id, s1);
  equal((await day()).attendance[0].enrollment_id, e1b); // Visible in the assigned batch although sign-in used another batch.
  result = await club('import', { ...payload, enrollment_ids: [e1, e1b, e2, e2] });
  equal(result.added, 0); equal(result.already_recorded, 2);
  equal((await day()).sessions.length, 1);
  await club('import', { ...payload, module: 'writing', enrollment_ids: [e1] });
  await club('import', { ...payload, club_date: '2026-09-19', enrollment_ids: [e2] });
  equal((await day()).sessions.length, 2);
  equal((await day(campus, '2026-09-19')).sessions.length, 1);
  equal((await day(campus, '2026-09-19')).attendance.length, 0);
  await reject(() => club('import', { ...payload, module: 'listening', enrollment_ids: [e1, e3] }), /not enrolled/);
  equal((await day()).sessions.some(s => s.module === 'listening'), false);
  await reject(() => club('import', { ...payload, branch_id: otherCampus, enrollment_ids: [e3] }), /cannot import/);
  await reject(() => roster(otherCampus), /cannot import/);
  await reject(() => day(otherCampus), /outside your access/);
  await reject(() => club('import', { ...payload, club_date: '2100-01-01' }), /today or earlier/);
  await reject(() => club('import', { ...payload, club_date: '2026-02-30' }), /date/);
  await reject(() => club('import', { ...payload, club_date: '2026-08-31' }), /not enrolled/);
  await reject(() => club('import', { ...payload, module: 'grammar' }), /Choose Listening/);
  await reject(() => club('import', { ...payload, enrollment_ids: [] }), /between 1 and 300/);
  await reject(() => club('import', { ...payload, enrollment_ids: [null] }), /not enrolled/);
  await reject(() => club('import', { ...payload, enrollment_ids: ['00000000-0000-4000-8000-999999999999'] }), /not enrolled/);
  await reject(() => club('import', { ...payload, enrollment_ids: Array(301).fill(e1) }), /between 1 and 300/);
  await reject(() => club('import', { ...payload, enrollment_ids: 'bad' }), /Choose the students/);
  await reject(() => q("insert into public.club_sessions(branch_id,club_date,module) values($1,'2026-09-20','reading')", [campus]), /permission denied/);
  await reject(() => q('delete from public.club_attendance'), /permission denied/);
  const beforeCorrection = await day();
  const entry = beforeCorrection.attendance.find(a => a.session_id === beforeCorrection.sessions.find(s => s.module === 'speaking').id);
  await club('remove', { attendance_id: entry.id });
  equal((await day()).attendance.length, 1);
  await reject(() => club('remove', { attendance_id: entry.id }), /already been removed/);
  result = await club('import', { ...payload, enrollment_ids: [e1] });
  equal(result.added, 1);
  await as('front');
  equal((await day()).attendance.length, 3);
  equal((await roster()).length, 3);
  equal((await club('import', { ...payload, module: 'reading', enrollment_ids: [e2] })).added, 1);
  await as('coordinator');
  equal((await club('import', { ...payload, module: 'listening', enrollment_ids: [e1] })).added, 1);
  const protectedEntry = (await day()).attendance[0].id;
  for (const role of ['viewer', 'counselor', 'pending', 'anon']) {
    await as(role);
    await reject(() => roster(), /cannot import|permission denied/);
    await reject(() => club('import', payload), /cannot import|activated|permission denied/);
    await reject(() => club('remove', { attendance_id: protectedEntry }), /cannot correct|activated|permission denied/);
    if (['viewer', 'counselor'].includes(role)) equal((await day()).attendance.length, 5);
    else await reject(() => day(), /outside your access|permission denied/);
  }
  await as('admin');
  equal((await club('import', { branch_id: otherCampus, club_date: '2026-09-20', module: 'speaking', enrollment_ids: [e3] })).added, 1);
  const otherEntry = (await day(otherCampus)).attendance[0];
  await as('teacher');
  await reject(() => club('remove', { attendance_id: otherEntry.id }), /cannot correct/);
  await as('admin');
  await write('update_enrollment', { id: e1, student_id: s1, status: 'completed' });
  equal((await day()).attendance.filter(a => a.student_id === s1).length, 3);
  await db.exec('reset role');
  await q('update public.students set deleted_at=clock_timestamp() where id=$1', [s2]);
  await as('teacher');
  equal((await roster()).some(r => r.student_id === s2), false);
  await reject(() => club('import', { ...payload, module: 'reading' }), /not enrolled/);
  await db.exec('reset role');
  equal((await q("select count(*)::int n from pg_class where relname in ('club_sessions','club_attendance') and relrowsecurity")).rows[0].n, 2);
  equal((await q("select count(*)::int n from public.audit_logs where action='remove_club_attendance' and old_values is not null")).rows[0].n, 1);
  console.log(`PASS: ${checks} club database checks: cross-batch imports, unique student attendance, date/module isolation, atomic saves, corrections, retained history and role/campus isolation.`);
} finally { await db.close(); }
